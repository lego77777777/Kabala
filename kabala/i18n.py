_STRINGS = {"he": HE, "en": EN}
_lang = "he"


def set_language(lang: str) -> None:
    global _lang
    _lang = lang if lang in _STRINGS else "he"


def language() -> str:
    return _lang


def is_rtl() -> bool:
    return _lang == "he"


def t(key: str, **kwargs: Any) -> Any:
    """t("scan.phase.done") → string; lists/tuples are returned as-is; {placeholders} are filled from kwargs."""
    node: Any = _STRINGS[_lang]
    for part in key.split("."):
        node = node[part]
    return node.format(**kwargs) if isinstance(node, str) and kwargs else node


# ---- formatting -------------------------------------------------------------

_SYMBOLS = {"ILS": "₪", "USD": "$", "EUR": "€", "GBP": "£"}


def money(amount: float, currency: str) -> str:
    sym = _SYMBOLS.get(currency.upper())
    num = f"{amount:,.2f}"
    if sym is None:
        return f"{num} {currency}"
    # Hebrew convention puts ₪ after the number; English before.
    return f"⁦{num} {sym}⁩" if is_rtl() else f"{sym}{num}"


def money_totals(totals: dict[str, float]) -> str:
    items = sorted(totals.items(), key=lambda kv: -kv[1])
    return " + ".join(money(v, c) for c, v in items) if items else money(0, "ILS")


def month_label(ym: str, long: bool = False) -> str:
    y, m = ym.split("-")
    name = t("months")[int(m) - 1]
    return f"{name} {y}" if long else f"{name} {y[2:]}"


def short_date(iso: str) -> str:
    y, m, d = iso.split("-")
    return f"{int(d)} {t('months')[int(m) - 1]} {y}"
